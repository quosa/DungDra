from __future__ import annotations


def _ab(s):
    keys = ["str", "dex", "con", "int", "wis", "cha"]
    return dict(zip(keys, s))


def atk(name, bonus, dmg, dtype, kind="melee", reach=5, rng=None, extra=None, adv_extra=None, on_hit=None,
        weapon=None):
    return {"name": name, "bonus": bonus, "damage": dmg, "dtype": dtype, "kind": kind, "reach": reach,
            "range": rng, "extra": extra or [], "adv_extra": adv_extra, "on_hit": on_hit, "weapon": weapon}


